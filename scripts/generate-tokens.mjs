import { readFile, writeFile } from 'node:fs/promises';
const source = JSON.parse(await readFile(new URL('../_ds/tokens/civicmaps.tokens.json', import.meta.url), 'utf8'));
const tokens = {};
for (const name of ['civic-primary', 'civic-secondary', 'civic-accent']) tokens[`--${name}`] = source.brand[name].$value;
for (const [name, value] of Object.entries(source.brand.neutral)) tokens[`--civic-neutral-${name}`] = value;
tokens['--civic-surface'] = source.brand.surface.default;
for (const [name, values] of Object.entries(source['semantic-status'])) {
  if (name.startsWith('$')) continue;
  for (const [key, value] of Object.entries(values)) {
    if (key.startsWith('$') && key !== '$value') continue;
    tokens[`--status-${name}${key === '$value' ? '' : `-${key}`}`] = value;
  }
}
for (const name of ['font-primary', 'font-mono', 'font-display']) tokens[`--${name}`] = source.typography[name];
const css = `/* Generated by scripts/generate-tokens.mjs from the canonical CivicMAPS tokens. */\n@font-face { font-family: 'DM Sans'; src: url('../../../_ds/fonts/DMSans-VariableFont_opsz_wght.ttf') format('truetype'); font-weight: 100 900; font-display: swap; }\n:root {\n${Object.entries(tokens).map(([name, value]) => `  ${name}: ${value};`).join('\n')}\n}\n`;
await writeFile(new URL('../apps/commandmaps/src/tokens.css', import.meta.url), css);
console.log('Canonical CivicMAPS tokens generated');
